export function hashOf(str) {
  // 演示用简易哈希；正式版由电子签平台返回内容哈希与证书链（第二十一条：序列号与有效期）
  let h = 5381
  for (let i = 0; i < str.length; i++) h = ((h * 33) ^ str.charCodeAt(i)) >>> 0
  return h.toString(16).padStart(8, '0').repeat(4).slice(0, 64)
}
