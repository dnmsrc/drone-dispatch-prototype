export function clauseCount() {
  return DISCLOSURE_SECTIONS.reduce((n, s) => n + s.items.length, 0)
}

/** 确认记录：{ v, at, user }。同一版本只确认一次；版本变了必须重新确认。 */
export function ackedFor(acks, version) {
  return (acks || []).some(e => e && e.v === version)
}

export function latestAck(acks) {
  const a = acks || []
  return a.length ? a[a.length - 1] : null
}

