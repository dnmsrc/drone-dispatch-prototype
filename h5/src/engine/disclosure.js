// 单勾只能证明「给过文本」，证不了「已尽提示与说明义务」——民法典第四百九十六条第二款，
// 且已尽提示或说明义务的举证责任在提供格式条款的一方（合同编通则司法解释）。
// 标记用「分组 + 组内序号」，不写死全局编号：编号会随条款增删变化，标记必须跟着条款走。
export const RISK_ITEMS = {
  '主体与身份': [4],
  '场地与判定': [4],
  '规模与容量': [1],
  '时段与审批': [0, 4],
  '观众与许可': [0, 2, 3],
  '资质与合规': [2],
  '费用与付款': [0, 1, 2],
  '风险与后果归属': [0, 2],
  '违规成本与罚则归属': [1, 2],
  '个人信息与数据': [3]
}

export function isRisk(title, indexInGroup) {
  return (RISK_ITEMS[title] || []).includes(indexInGroup)
}

// ── 逐条确认的「触点」（2026-10-28 六次调整，用户要求）────────────────────────
// 重大利害关系条款不在流程入口一次性确认，也不在填写途中打断 —— 统一在下一步/提交/签署时确认本步适用条款。
// 触点 = 页面上那个可点的元素；确认发生在用户真的碰到这条条款的那个时刻，
// 这比一个总勾更能证明「已对该条尽到提示与说明义务」（民法典第四百九十六条第二款）。
// 映射仍用「组名 + 组内序号」，不写全局编号（同 RISK_ITEMS 的约束：编号随条款增删变化）。
export const TOUCH_CLAUSE = {
  venuePermit:      ['风险与后果归属', 2],      // 场地管理部门未同意 → 责任在甲方
  airspacePenalty:  ['违规成本与罚则归属', 2],  // 未经批准在管制空域飞行
  capacity:         ['规模与容量', 1],          // 静态上限 ≠ 当日评估容量
  audience:         ['观众与许可', 0],          // 观众数必填 + 许可层级 + 后果归属
  securityStaff:    ['观众与许可', 2],          // 圈层防护 + 甲方负责现场安保人数
  crowdLicense:     ['观众与许可', 3],          // 1000 人以上需安全许可 · 20 日前
  networkIsolation: ['资质与合规', 2],          // 物理隔离；要求现场联网须另行约定
  feeWaiver:        ['场地与判定', 4],          // 判定费免除的三条件
  slotResult:       ['时段与审批', 0],          // 时段是审批结果，不是甲方选项
  reschedule:       ['时段与审批', 4],          // 改期 = 重新审批 + 加急费 + 政务不收费
  decisionDay:      ['风险与后果归属', 0],      // 当日是否举行由公安机关决定
  quoteRange:       ['费用与付款', 0],          // 线上只给区间，不构成要约
  paymentNodes:     ['费用与付款', 1],          // 付款节点 · 定金不可退 · 逾期违约金
  priceLayers:      ['费用与付款', 2],          // 报价四层 · 未确认项不作为承诺
  responsibility:   ['主体与身份', 4],          // 责任主体三条线
  penaltyPartyA:    ['违规成本与罚则归属', 1],  // 甲方侧罚则（未经安全许可）
  sensitiveId:      ['个人信息与数据', 3]       // 身份证件号码：必须独立动作，不能并入总勾
}

// 组名 + 组内序号 → 全局条款号
function clauseNo(title, i) {
  let n = 0
  for (const s of DISCLOSURE_SECTIONS) {
    if (s.title === title) return n + i + 1
    n += s.items.length
  }
  return 0
}

export function clauseOf(touch) {
  const m = TOUCH_CLAUSE[touch]
  if (!m) return null
  const [title, i] = m
  const s = DISCLOSURE_SECTIONS.find(x => x.title === title)
  return { touch, group: title, n: clauseNo(title, i), text: s ? s.items[i] : '' }
}

// 反向：条款 → 触点（须知页按条款列出，点某条时要能跳回它对应的那个入口）
export function touchOf(title, indexInGroup) {
  return Object.keys(TOUCH_CLAUSE).find(k => TOUCH_CLAUSE[k][0] === title && TOUCH_CLAUSE[k][1] === indexInGroup) || ''
}

/** 这一条对本单是否成立：只有真的被触发的条款才需要确认（用户：不该一上来就确认全部）。 */
export function appliesTo(touch, a) {
  if (!a) return false
  switch (touch) {
    case 'crowdLicense':
    case 'penaltyPartyA': return (a.need && a.need.audience >= 1000)
    case 'airspacePenalty': return !!(a.venue && a.venue.airspace === 'controlled')
    case 'venuePermit': return !!(a.venue && a.venue.permit !== 'GRANTED')
    case 'feeWaiver': return !!(a.judgment && a.judgment.fee && a.judgment.fee.payable > 0)
    default: return true
  }
}

/** 已确认的条款号（当前版本）。兼容旧的整批记录（risk 数组）。 */
export function confirmedClauses(acks, version) {
  const out = new Set()
  for (const e of acks || []) {
    if (!e || e.v !== version) continue
    if (e.clause) out.add(e.clause)
    for (const n of e.risk || []) out.add(n)
  }
  return [...out]
}

// 触点属于哪一步 = 它在哪一页被触发/出现。门只拦「这一步及之前真的遇到的条款」：
// 用户要求不该一上来确认全部 —— 第 1 步的门只该有场地的 2 条，不该把后面 15 条一起摆出来。
export const TOUCH_STEP = {
  venuePermit: 1, airspacePenalty: 1,
  capacity: 2, audience: 2, feeWaiver: 2, securityStaff: 2, networkIsolation: 2,
  crowdLicense: 2, penaltyPartyA: 2, slotResult: 3, decisionDay: 3, reschedule: 3,
  quoteRange: 4, priceLayers: 4, paymentNodes: 4,
  responsibility: 6, sensitiveId: 6
}

/** 本单适用、但还没确认的触点 —— 门只看「已经走到的那几步里触发的条款」。 */
export function pendingTouches(a, version, maxStep) {
  const v = version || DISCLOSURE_VERSION
  const got = confirmedClauses(a && a.acks, v)
  const upto = maxStep || Object.keys(TOUCH_STEP).length
  return Object.keys(TOUCH_CLAUSE).filter(t => (TOUCH_STEP[t] || 99) <= upto && appliesTo(t, a) && !got.includes(clauseOf(t).n))
}

export function riskNumbers() {
  const out = []
  let n = 0
  for (const s of DISCLOSURE_SECTIONS) {
    s.items.forEach((t, i) => { n++; if ((RISK_ITEMS[s.title] || []).includes(i)) out.push(n) })
  }
  return out
}

// 确认时的内容哈希：电子签名法第十三条要求「签署后对内容的任何改动能够被发现」。
export function contentHash() {
  return hashOf(DISCLOSURE_VERSION + '|' + DISCLOSURE_SECTIONS.map(s => s.title + '|' + s.items.join('|')).join('||'))
}

// 确认记录是否完整：版本必须匹配，且重大利害关系条款必须逐条确认过。
export function ackComplete(acks, version) {
  const a = latestAck(acks)
  if (!a || a.v !== version) return false
  const need = riskNumbers()
  const got = a.risk || []
  return need.every(n => got.includes(n))
}

export function fullText() {
  let n = 0
  const body = DISCLOSURE_SECTIONS.map(s => `【${s.title}】\n` + s.items.map(t => `${++n}. ${t}`).join('\n')).join('\n\n')
  return `《申请说明（告知确认书）》 ${DISCLOSURE_VERSION}\n${body}\n\n内容哈希：${contentHash()}`
}
