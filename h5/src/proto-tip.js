export function installProtoTip() {
  if (typeof document === 'undefined') return // 非 H5 平台（如小程序）不注入
  const style = document.createElement('style')
  style.textContent = CSS
  document.head.appendChild(style)

  const badge = document.createElement('div')
  badge.id = 'proto-tip-badge'
  badge.textContent = '?'
  const card = document.createElement('div')
  card.id = 'proto-tip-card'
  document.body.appendChild(badge)
  document.body.appendChild(card)

  let pinned = false
  let hover = false

  function currentPath() {
    const h = location.hash.replace(/^#/, '')
    return h.split('?')[0] || '/pages/index/index'
  }

  function render() {
    const tip = TIPS[currentPath()]
    if (!tip) {
      badge.style.display = 'none'
      card.style.display = 'none'
      pinned = hover = false
      return
    }
    badge.style.display = 'block'
    card.innerHTML =
      '<div class="pt-head"><span class="pt-tag">原型说明</span><span class="pt-title">' +
      tip.title + '</span><span class="pt-close">×</span></div>' +
      tip.lines.map((l) => '<p class="pt-line">' + l + '</p>').join('') +
      '<div class="pt-foot">仅评审辅助展示，正式系统不包含此说明</div>'
    card.querySelector('.pt-close').onclick = (e) => {
      e.stopPropagation()
      pinned = hover = false
      sync()
    }
    place()
    // 关键：render() 原来只校正位置、没有调用 sync()，而 #proto-tip-card 是个默认 display:block 的 div，
    // 于是每次页面加载时说明卡都是「展开」状态，固定 300×最高 420px 的白卡正好盖在右下角内容上——
    // 「联系人输入框点不动、真实键盘输入落进 BODY」就是这么来的（elementFromPoint 命中的是 .pt-line）。
    // 补这一句后初始就是收起的，和管理端 ProtoTip.vue 的 v-show="hover || pinned" 行为一致。
    sync()
  }

  function bottomObstacle() {
    // 右下角要落在这页面自带的底部固定条（price-bar / TabBar）之上，不能压住「下一步」这类主按钮
    const app = document.getElementById('app')
    const vh = window.innerHeight
    let occ = 0
    const nodes = app ? app.querySelectorAll('*') : []
    for (const n of nodes) {
      if (n.id && n.id.indexOf('proto-tip') === 0) continue
      if (window.getComputedStyle(n).position !== 'fixed') continue
      const r = n.getBoundingClientRect()
      if (r.width < 80) continue
      if (r.bottom < vh - 3) continue      // 只认贴住屏幕下边缘的条
      if (r.top < vh * 0.55) continue      // 贯穿整屏的遮罩不算
      occ = Math.max(occ, vh - r.top)
    }
    return occ
  }

  function place() {
    // 贴住 #app 容器右边缘（桌面演示时 #app 以手机宽度居中），底部让开页面自己的固定底栏
    const app = document.getElementById('app')
    const rect = app ? app.getBoundingClientRect() : { left: 0, right: window.innerWidth }
    const right = Math.max(12, Math.round(window.innerWidth - rect.right + 12))
    const bottom = bottomObstacle() + 14
    const set = (el, style) => {
      el.style.left = 'auto'
      el.style.top = 'auto'
      el.style.right = right + 'px'
      el.style.bottom = style + 'px'
    }
    set(badge, bottom)
    set(card, bottom + 30)
  }

  function sync() {
    card.style.display = pinned || hover ? 'block' : 'none'
  }

  badge.addEventListener('mouseenter', () => { hover = true; sync() })
  badge.addEventListener('mouseleave', () => { hover = false; sync() })
  card.addEventListener('mouseenter', () => { hover = true; sync() })
  card.addEventListener('mouseleave', () => { hover = false; sync() })
  badge.addEventListener('click', (e) => { e.stopPropagation(); pinned = !pinned; sync() })
  document.addEventListener('click', () => { if (pinned) { pinned = false; sync() } })

  function refresh() {
    render()
    // 页面渲染是异步的，延迟再校正一次位置
    setTimeout(place, 200)
    setTimeout(place, 700)
  }

  window.addEventListener('hashchange', refresh)
  window.addEventListener('resize', place)
  refresh()
}
