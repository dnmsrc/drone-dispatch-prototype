import puppeteer from 'puppeteer-core'
const EDGE = 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'
const sleep = ms => new Promise(r => setTimeout(r, ms))
const b = await puppeteer.launch({ executablePath: EDGE, headless: false, args: ['--no-sandbox'] })
const p = await b.newPage()
await p.setViewport({ width: 480, height: 900 })
p.on('dialog', d => d.accept().catch(() => {}))
p.on('pageerror', e => console.log('pageerror', e.message.slice(0, 150)))
const t0 = Date.now()
await p.goto('http://localhost:8090/#/pages/login/login', { waitUntil: 'networkidle2' })
await p.reload({ waitUntil: 'networkidle2' })
await sleep(1000)
await p.evaluate(() => { const e = [...document.querySelectorAll('.wx-btn')].find(x => x.getClientRects().length); e && e.click() })
await sleep(800)
await p.evaluate(() => { const b = document.querySelector('.btn.allow'); b && b.click() })
await sleep(1200)
console.log('login+home', Date.now() - t0, 'ms')
await p.goto('http://localhost:8090/#/pages/order/list', { waitUntil: 'networkidle2' })
await p.reload({ waitUntil: 'networkidle2' })
await sleep(1200)
console.log('order list loaded', Date.now() - t0, 'ms')
await p.evaluate(() => document.querySelector('.order-card').click())
await sleep(1200)
const s1 = await p.evaluate(() => ({ hash: location.hash, banner: !!document.querySelector('.banner') }))
console.log('detail', JSON.stringify(s1))
await p.evaluate(() => { const el = [...document.querySelectorAll('button, [class*=btn]')].find(e => (e.innerText || '').includes('申请退款') && e.getClientRects().length); el && el.click() })
await sleep(1500)
const s2 = await p.evaluate(() => ({ hash: location.hash, calc: !!document.querySelector('.calc-card') }))
console.log('refund', JSON.stringify(s2), 'total', Date.now() - t0, 'ms')
await b.close()
